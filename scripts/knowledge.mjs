// Builds worker/knowledge.generated.ts from knowledge/*.md.
// Lines with "[PREENCHER" and <!-- comments --> never reach the prompt.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "knowledge");
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".md") && f.toLowerCase() !== "readme.md")
  .sort();

let pending = 0;
const parts = files.map((f) => {
  const text = readFileSync(join(dir, f), "utf8").replace(/<!--[\s\S]*?-->/g, "");
  const kept = text.split("\n").filter((line) => {
    if (line.includes("[PREENCHER")) {
      pending += 1;
      return false;
    }
    return true;
  });
  return kept.join("\n").trim();
});

const knowledge = parts.filter(Boolean).join("\n\n---\n\n");
const body = `// GENERATED by scripts/knowledge.mjs from knowledge/*.md. Do not edit by hand.\nexport const KNOWLEDGE = ${JSON.stringify(knowledge)};\n`;
writeFileSync(join(root, "worker", "knowledge.generated.ts"), body);
console.log(`knowledge: ${files.length} files, ${knowledge.length} chars (~${Math.round(knowledge.length / 4)} tokens), ${pending} [PREENCHER] lines left out`);
